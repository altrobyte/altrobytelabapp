"""Copy the code the desktop trainer needs from the main app into desktop_app/.

One source of truth: edit lib/ in the main project, then run

    python tools/sync_desktop_app.py            # copy
    python tools/sync_desktop_app.py --check    # exit 1 if desktop_app/ is out of date (used by a test)

The set of files is not listed by hand: it is whatever lib/desktop/desktop_main.dart
imports, followed recursively. If the desktop app ever starts importing something
web-only (dart:html, package:web, Firebase), this script refuses, because that code
cannot be compiled into a Windows app.
"""
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ENTRY = "lib/desktop/desktop_main.dart"
DEST = os.path.join(ROOT, "desktop_app")
FORBIDDEN = re.compile(r"^\s*import\s+'(dart:html|dart:ui_web|dart:js|dart:js_interop|package:web/|package:firebase|package:google_sign_in)", re.M)

# Pages the app ships inside itself (served to its browser view from its own folder), copied from the website's source.
ASSETS = {"web/live/v2/index.html": "assets/live/index.html"}

MAIN_DART = """// Generated by tools/sync_desktop_app.py - do not edit.
import 'desktop/desktop_main.dart' as app;

Future<void> main() => app.main();
"""


def closure():
    seen, order = set(), []

    def walk(rel):
        p = os.path.normpath(rel)
        if p in seen:
            return
        full = os.path.join(ROOT, p)
        if not os.path.exists(full):
            raise SystemExit(f"Missing file imported by the desktop app: {p}")
        seen.add(p)
        order.append(p)
        text = open(full, encoding="utf-8").read()
        bad = FORBIDDEN.search(text)
        if bad:
            raise SystemExit(f"{p} imports {bad.group(1)}, which cannot be built into a Windows app.")
        for m in re.finditer(r"^import\s+'([^']+)'", text, re.M):
            t = m.group(1)
            if t.startswith("package:altrobytelab/"):
                walk("lib/" + t.split("/", 1)[1])
            elif not t.startswith(("dart:", "package:")):
                walk(os.path.join(os.path.dirname(p), t))

    walk(ENTRY)
    return sorted(order)


def read(path):
    with open(path, "rb") as f:
        return f.read().replace(b"\r\n", b"\n")      # line endings differ per checkout; content is what matters


def main(check: bool) -> int:
    stale = []
    files = closure()
    for rel in files:
        src, dst = os.path.join(ROOT, rel), os.path.join(DEST, rel)
        if not os.path.exists(dst) or read(src) != read(dst):
            stale.append(rel)
            if not check:
                os.makedirs(os.path.dirname(dst), exist_ok=True)
                shutil.copyfile(src, dst)
    main_path = os.path.join(DEST, "lib", "main.dart")
    if not os.path.exists(main_path) or read(main_path) != MAIN_DART.encode().replace(b"\r\n", b"\n"):
        stale.append("lib/main.dart")
        if not check:
            with open(main_path, "w", encoding="utf-8", newline="\n") as f:
                f.write(MAIN_DART)
    for src_rel, dst_rel in ASSETS.items():
        src, dst = os.path.join(ROOT, src_rel), os.path.join(DEST, dst_rel)
        if not os.path.exists(dst) or read(src) != read(dst):
            stale.append(dst_rel)
            if not check:
                os.makedirs(os.path.dirname(dst), exist_ok=True)
                shutil.copyfile(src, dst)
    # Copies of files the app no longer imports would be dead weight that still gets analysed.
    keep = {os.path.normpath(f) for f in files} | {os.path.normpath("lib/main.dart")}
    for base, _, names in os.walk(os.path.join(DEST, "lib")):
        for n in names:
            rel = os.path.normpath(os.path.relpath(os.path.join(base, n), DEST))
            if rel not in keep:
                stale.append(f"(extra) {rel}")
                if not check:
                    os.remove(os.path.join(DEST, rel))
    if check:
        if stale:
            print("desktop_app is out of date; run: python tools/sync_desktop_app.py\n  " + "\n  ".join(stale))
            return 1
        print(f"desktop_app is in sync ({len(files)} files).")
        return 0
    print(f"synced {len(files)} files into desktop_app/lib" + (f" ({len(stale)} changed)" if stale else " (already up to date)"))
    return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
